def record_finops_recommendation(
    category: str,
    confidence_score: float,
    savings_type: str,
    monthly_savings: float = 0.0,
) -> None:
    """Record FinOps recommendation generation and cumulative potential savings."""
    allowed_cats = ("compute", "storage", "database", "network", "anomaly", "general")
    safe_cat = category.lower() if category.lower() in allowed_cats else "general"
    safe_type = (
        savings_type.lower() if savings_type.lower() in ("guaranteed", "estimated") else "estimated"
    )

    if confidence_score >= 0.8:
        conf_tier = "high"
    elif confidence_score >= 0.5:
        conf_tier = "medium"
    else:
        conf_tier = "low"

    FINOPS_RECOMMENDATIONS_TOTAL.labels(
        category=safe_cat,
        confidence_tier=conf_tier,
        savings_type=safe_type,
    ).inc()

    if monthly_savings > 0:
        FINOPS_SAVINGS_IDENTIFIED_DOLLARS.labels(
            savings_type=safe_type,
            category=safe_cat,
        ).inc(monthly_savings)


def record_finops_anomaly_identified(severity: str) -> None:
    """Increment counter for detected spending anomaly by severity."""
    safe_sev = (
        severity.upper() if severity.upper() in ("LOW", "MEDIUM", "HIGH", "CRITICAL") else "MEDIUM"
    )
    FINOPS_ANOMALIES_IDENTIFIED_TOTAL.labels(severity=safe_sev).inc()


def get_prometheus_exposition(force_refresh: bool = False) -> bytes:
    """Retrieve Prometheus metrics payload in standard exposition format."""
    return _METRICS_CACHE.get_exposition(force_refresh=force_refresh)
